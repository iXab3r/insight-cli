import test from 'node:test';
import assert from 'node:assert/strict';
import{mkdtemp,writeFile,rm}from'node:fs/promises';
import{join}from'node:path';
import{tmpdir}from'node:os';
import{Workspace}from'../src/workspace.js';
test('publication intent survives restart, blocks every session of the shared target, and commits acknowledgment atomically',async t=>{
 const root=await mkdtemp(join(tmpdir(),'insight-pub-')),stores:Workspace[]=[];
 const open=()=>{const store=new Workspace(root,'default');stores.push(store);return store;};
 t.after(async()=>{for(const store of stores)store.close();await rm(root,{recursive:true,force:true});});
 const store=open(),input=join(root,'fixture.exe');await writeFile(input,'synthetic executable');const target=await store.importTarget(input);
 const a=store.reserveOpen(target.id,'new',{autoAnalyze:true}).context,b=store.reserveOpen(target.id,'new',{autoAnalyze:true}).context;
 const baseFile=join(root,'base.gzf'),candidateFile=join(root,'candidate.gzf');await writeFile(baseFile,'synthetic base');await writeFile(candidateFile,'synthetic candidate');
 const base=await store.captureSnapshot(baseFile),candidate=await store.captureSnapshot(candidateFile);store.establishModel(target.id,1,base);
 for(const context of [a,b])store.saveContext(context,0,{state:'ready',baseRevision:1,baseSnapshot:base,workingSnapshot:base});
 const changed=store.saveContext(a,1,{workingSnapshot:candidate,scalars:[{address:'1000',field:'comment.eol',original:null,local:'A'}]});
 const intent=store.reserveRequest(a,'ghidra.merge',{},'merge-A').request;store.startRequest(intent.id);
 const publication=store.beginPublication(a,intent.id,1,candidate);store.publicationIntent(publication.id);
 const reopened=open();assert.equal(reopened.model(target.id).state,'unknown');assert.equal(reopened.activePublication(target.id)?.id,publication.id);
 const other=reopened.reserveRequest(b,'ghidra.merge',{},'merge-B').request;reopened.startRequest(other.id);
 assert.throws(()=>reopened.beginPublication(b,other.id,1,candidate),/unresolved publication/);
 store.unknownPublication(publication.id,{state:'unknown'});store.recordRequest(intent.id,'unknown',{state:'unknown'});
 assert.throws(()=>store.rejectPublication(publication.id,{state:'conflict'}),/cannot be abandoned/);
 const result={session:a.session,target:target.id,state:'merged',sharedRevision:'R2',applied:1,pendingChanges:0};
 reopened.finishPublication(publication.id,2,result);
 assert.equal(store.model(target.id).state,'ready');assert.equal(store.activePublication(target.id),undefined);
 assert.equal(store.context(a).generation,changed.generation+1);assert.equal(store.context(a).baseRevision,2);assert.deepEqual(store.context(a).scalars,[]);
 assert.equal(store.context(b).baseRevision,1);assert.equal(store.context(b).workingSnapshot?.id,base.id);
 assert.deepEqual(store.reserveRequest(a,'ghidra.merge',{},'merge-A').request.result,result);
 assert.equal(store.publishedSince(target.id,1).length,1);
});
test('stale private generation prevents false verified publication and preserves unknown lane',async t=>{
 const root=await mkdtemp(join(tmpdir(),'insight-pub-')),store=new Workspace(root,'default');
 t.after(async()=>{store.close();await rm(root,{recursive:true,force:true});});
 const input=join(root,'fixture.exe');await writeFile(input,'fixture');const target=await store.importTarget(input);
 const context=store.reserveOpen(target.id,'new',{autoAnalyze:true}).context,file=join(root,'base.gzf');await writeFile(file,'synthetic snapshot');
 const snapshot=await store.captureSnapshot(file);store.establishModel(target.id,1,snapshot);
 store.saveContext(context,0,{state:'ready',baseRevision:1,baseSnapshot:snapshot,workingSnapshot:snapshot});
 const request=store.reserveRequest(context,'ghidra.merge',{}).request;store.startRequest(request.id);
 const publication=store.beginPublication(context,request.id,1,snapshot);store.publicationIntent(publication.id);
 store.saveContext(context,1,{complexChanges:['later-edit']});
 assert.throws(()=>store.finishPublication(publication.id,2,{state:'merged'}),/changed during publication/);
 assert.equal(store.model(target.id).state,'unknown');assert.equal(store.request(request.id).state,'running');
 assert.equal(store.context(context).complexChanges[0],'later-edit');assert.ok(store.activePublication(target.id));
});
